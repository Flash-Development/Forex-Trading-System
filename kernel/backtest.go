// GenerateSimpleSignals creates basic EMA-crossover signals from OHLCV bars.
// This is a fallback when no explicit signals are provided.
func GenerateSimpleSignals(symbol string, bars []BacktestBar, riskPct float64) []BacktestSignal {
	if len(bars) < 50 {
		return nil
	}

	const fastPeriod = 20
	const slowPeriod = 50
	const atrPeriod = 14
	const rrRatio = 2.0

	closes := make([]float64, len(bars))
	for i, b := range bars {
		closes[i] = b.Close
	}

	fast := EMA(closes, fastPeriod)
	slow := EMA(closes, slowPeriod)
	atrVals := ATR(bars, atrPeriod)

	pip := PipSize(symbol)
	minSLPips := 20.0

	var signals []BacktestSignal
	for i := slowPeriod + 1; i < len(bars); i++ {
		prevFast := fast[i-1]
		prevSlow := slow[i-1]
		curFast := fast[i]
		curSlow := slow[i]
		price := bars[i].Close
		atrVal := atrVals[i]
		if atrVal <= 0 {
			continue
		}

		slDist := atrVal * 1.5
		if slDist/pip < minSLPips {
			slDist = minSLPips * pip
		}

		// Bullish crossover
		if prevFast <= prevSlow && curFast > curSlow {
			signals = append(signals, BacktestSignal{
				Time:       bars[i].Time,
				Symbol:     symbol,
				Side:       "long",
				EntryPrice: price,
				StopLoss:   price - slDist,
				TakeProfit: price + slDist*rrRatio,
			})
		}
		// Bearish crossover
		if prevFast >= prevSlow && curFast < curSlow {
			signals = append(signals, BacktestSignal{
				Time:       bars[i].Time,
				Symbol:     symbol,
				Side:       "short",
				EntryPrice: price,
				StopLoss:   price + slDist,
				TakeProfit: price - slDist*rrRatio,
			})
		}
	}
	return signals
}

// EMA calculates exponential moving average.
func EMA(prices []float64, period int) []float64 {
	result := make([]float64, len(prices))
	if len(prices) < period {
		return result
	}
	k := 2.0 / float64(period+1)
	sum := 0.0
	for i := 0; i < period; i++ {
		sum += prices[i]
	}
	result[period-1] = sum / float64(period)
	for i := period; i < len(prices); i++ {
		result[i] = prices[i]*k + result[i-1]*(1-k)
	}
	return result
}

// ATR calculates Average True Range.
func ATR(bars []BacktestBar, period int) []float64 {
	result := make([]float64, len(bars))
	if len(bars) < period+1 {
		return result
	}
	trs := make([]float64, len(bars))
	for i := 1; i < len(bars); i++ {
		h := bars[i].High
		l := bars[i].Low
		pc := bars[i-1].Close
		tr := h - l
		if h-pc > tr {
			tr = h - pc
		}
		if pc-l > tr {
			tr = pc - l
		}
		trs[i] = tr
	}
	sum := 0.0
	for i := 1; i <= period; i++ {
		sum += trs[i]
	}
	result[period] = sum / float64(period)
	for i := period + 1; i < len(bars); i++ {
		result[i] = (result[i-1]*float64(period-1) + trs[i]) / float64(period)
	}
	return result
}
