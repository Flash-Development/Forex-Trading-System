package kernel

import (
	"math"
	"time"
)

// ============================================================================
// Backtest Types
// ============================================================================

// BacktestTrade represents a single completed trade in a backtest.
type BacktestTrade struct {
	Symbol     string
	Side       string // "long" | "short"
	EntryTime  time.Time
	ExitTime   time.Time
	EntryPrice float64
	ExitPrice  float64
	Lots       float64
	StopLoss   float64
	TakeProfit float64
	PnLUSD     float64
	PnLPct     float64 // as fraction of equity at entry
	RiskUSD    float64
	Pips       float64 // pips gained/lost
	IsWin      bool
}

// BacktestResult contains the full output of a backtest run.
type BacktestResult struct {
	Symbol          string
	StartDate       time.Time
	EndDate         time.Time
	InitialEquity   float64
	FinalEquity     float64
	TotalReturnPct  float64
	TotalTrades     int
	WinRate         float64
	ProfitFactor    float64
	SharpeRatio     float64
	MaxDrawdownPct  float64
	MaxDrawdownUSD  float64
	AvgWinPips      float64
	AvgLossPips     float64
	AvgRR           float64 // average realised risk:reward
	ExpectedValuePct float64 // EV per trade as % of equity
	Trades          []BacktestTrade
	EquityCurve     []EquityPoint
	MonteCarloResult *MonteCarloResult
}

// EquityPoint is a single point on the equity curve.
type EquityPoint struct {
	Time   time.Time
	Equity float64
}

// ============================================================================
// Backtest Engine
// ============================================================================

// BacktestConfig holds the parameters for a single backtest run.
type BacktestConfig struct {
	Symbol        string
	InitialEquity float64
	IsCentAccount bool
	RiskPctPerTrade float64 // e.g. 0.01 = 1%
	SpreadPips    float64   // simulated spread cost per trade
	CommissionUSD float64   // fixed commission per lot per side
	// Slippage in pips applied to entry/exit prices.
	SlippagePips float64
	// RunMonteCarlo enables Monte Carlo simulation after the base run.
	RunMonteCarlo bool
	MonteCarloRuns int
}

// BacktestBar is a single OHLCV bar used during simulation.
type BacktestBar struct {
	Time   time.Time
	Open   float64
	High   float64
	Low    float64
	Close  float64
	Volume float64
}

// BacktestSignal is a trade signal generated by a strategy during simulation.
type BacktestSignal struct {
	Time       time.Time
	Symbol     string
	Side       string  // "long" | "short"
	EntryPrice float64
	StopLoss   float64
	TakeProfit float64
	Lots       float64 // 0 = auto-size from risk %
}

// RunBacktest simulates a strategy over historical bars and returns metrics.
// signals must be sorted by Time ascending.
func RunBacktest(cfg BacktestConfig, signals []BacktestSignal, bars []BacktestBar) BacktestResult {
	equity := NormaliseCentAccountEquity(cfg.InitialEquity, cfg.IsCentAccount)
	peakEquity := equity

	result := BacktestResult{
		Symbol:        cfg.Symbol,
		InitialEquity: equity,
	}
	if len(bars) > 0 {
		result.StartDate = bars[0].Time
		result.EndDate = bars[len(bars)-1].Time
	}

	equityCurve := []EquityPoint{{Time: result.StartDate, Equity: equity}}
	maxDD := 0.0
	maxDDUSD := 0.0

	totalWins, totalLosses := 0, 0
	grossProfit, grossLoss := 0.0, 0.0
	sumWinPips, sumLossPips := 0.0, 0.0
	sumRR := 0.0

	// Build a bar index for fast lookup
	barByTime := make(map[time.Time]BacktestBar, len(bars))
	for _, b := range bars {
		barByTime[b.Time] = b
	}

	for _, sig := range signals {
		if equity <= 0 {
			break
		}

		// Determine lot size
		lots := sig.Lots
		if lots <= 0 && cfg.RiskPctPerTrade > 0 {
			slPips := math.Abs(sig.EntryPrice-sig.StopLoss) / PipSize(sig.Symbol)
			r := CalculateForexPositionSize(ForexPositionSizeRequest{
				Symbol:        sig.Symbol,
				AccountEquity: equity,
				RiskPct:       cfg.RiskPctPerTrade,
				StopLossPips:  slPips,
				CurrentPrice:  sig.EntryPrice,
			})
			lots = r.Lots
		}
		if lots <= 0 {
			lots = 0.01
		}

		// Apply spread & slippage to entry
		pip := PipSize(sig.Symbol)
		spreadCost := cfg.SpreadPips * pip
		slipCost := cfg.SlippagePips * pip
		entryAdj := sig.EntryPrice
		if sig.Side == "long" {
			entryAdj += spreadCost + slipCost
		} else {
			entryAdj -= spreadCost + slipCost
		}

		// Simulate outcome: check if SL or TP is hit first using subsequent bars
		exitPrice, exitTime := simulateExit(sig, entryAdj, bars, barByTime)

		// Apply slippage to exit
		if sig.Side == "long" {
			exitPrice -= slipCost
		} else {
			exitPrice += slipCost
		}

		// Calculate P&L
		pipVal := PipValuePerLot(sig.Symbol, entryAdj)
		var pips float64
		if sig.Side == "long" {
			pips = (exitPrice - entryAdj) / pip
		} else {
			pips = (entryAdj - exitPrice) / pip
		}
		pnl := pips * pipVal * lots
		// Subtract commission (both sides)
		pnl -= cfg.CommissionUSD * lots * 2

		slPips := math.Abs(entryAdj-sig.StopLoss) / pip
		tpPips := math.Abs(sig.TakeProfit-entryAdj) / pip
		rr := 0.0
		if slPips > 0 {
			rr = tpPips / slPips
		}

		trade := BacktestTrade{
			Symbol:     sig.Symbol,
			Side:       sig.Side,
			EntryTime:  sig.Time,
			ExitTime:   exitTime,
			EntryPrice: entryAdj,
			ExitPrice:  exitPrice,
			Lots:       lots,
			StopLoss:   sig.StopLoss,
			TakeProfit: sig.TakeProfit,
			PnLUSD:     pnl,
			PnLPct:     pnl / equity,
			RiskUSD:    cfg.RiskPctPerTrade * equity,
			Pips:       pips,
			IsWin:      pnl > 0,
		}
		result.Trades = append(result.Trades, trade)

		equity += pnl
		if equity > peakEquity {
			peakEquity = equity
		}
		dd := (peakEquity - equity) / peakEquity
		if dd > maxDD {
			maxDD = dd
			maxDDUSD = peakEquity - equity
		}

		equityCurve = append(equityCurve, EquityPoint{Time: exitTime, Equity: equity})

		if pnl > 0 {
			totalWins++
			grossProfit += pnl
			sumWinPips += pips
		} else {
			totalLosses++
			grossLoss += math.Abs(pnl)
			sumLossPips += math.Abs(pips)
		}
		sumRR += rr
	}

	n := len(result.Trades)
	result.FinalEquity = equity
	result.TotalReturnPct = (equity - result.InitialEquity) / result.InitialEquity
	result.TotalTrades = n
	result.MaxDrawdownPct = maxDD
	result.MaxDrawdownUSD = maxDDUSD
	result.EquityCurve = equityCurve

	if n > 0 {
		result.WinRate = float64(totalWins) / float64(n)
		if totalLosses > 0 {
			result.AvgLossPips = sumLossPips / float64(totalLosses)
		}
		if totalWins > 0 {
			result.AvgWinPips = sumWinPips / float64(totalWins)
		}
		if grossLoss > 0 {
			result.ProfitFactor = grossProfit / grossLoss
		}
		result.AvgRR = sumRR / float64(n)
		result.SharpeRatio = calcSharpe(result.Trades)
		result.ExpectedValuePct = (result.WinRate*result.AvgWinPips - (1-result.WinRate)*result.AvgLossPips) / result.AvgLossPips
	}

	if cfg.RunMonteCarlo && n > 0 {
		runs := cfg.MonteCarloRuns
		if runs <= 0 {
			runs = 1000
		}
		result.MonteCarloResult = RunMonteCarlo(result.Trades, result.InitialEquity, runs)
	}

	return result
}

// simulateExit finds the first bar after entry where SL or TP is hit.
func simulateExit(sig BacktestSignal, entryPrice float64, bars []BacktestBar, _ map[time.Time]BacktestBar) (float64, time.Time) {
	for _, b := range bars {
		if !b.Time.After(sig.Time) {
			continue
		}
		if sig.Side == "long" {
			if b.Low <= sig.StopLoss {
				return sig.StopLoss, b.Time
			}
			if b.High >= sig.TakeProfit {
				return sig.TakeProfit, b.Time
			}
		} else {
			if b.High >= sig.StopLoss {
				return sig.StopLoss, b.Time
			}
			if b.Low <= sig.TakeProfit {
				return sig.TakeProfit, b.Time
			}
		}
	}
	// No exit found — close at last bar close
	if len(bars) > 0 {
		last := bars[len(bars)-1]
		return last.Close, last.Time
	}
	return entryPrice, sig.Time
}

// calcSharpe computes an annualised Sharpe ratio from trade P&L percentages.
func calcSharpe(trades []BacktestTrade) float64 {
	if len(trades) < 2 {
		return 0
	}
	returns := make([]float64, len(trades))
	sum := 0.0
	for i, t := range trades {
		returns[i] = t.PnLPct
		sum += t.PnLPct
	}
	mean := sum / float64(len(returns))
	variance := 0.0
	for _, r := range returns {
		d := r - mean
		variance += d * d
	}
	variance /= float64(len(returns) - 1)
	stddev := math.Sqrt(variance)
	if stddev == 0 {
		return 0
	}
	// Annualise assuming ~252 trades per year
	return (mean / stddev) * math.Sqrt(252)
}

